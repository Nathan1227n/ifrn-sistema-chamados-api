CREATE TABLE setores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CHECK (btrim(nome) <> ''),
    sigla VARCHAR(20) NOT NULL CHECK (btrim(sigla) <> ''),
    CONSTRAINT uk_setores_sigla UNIQUE (sigla)
);
CREATE UNIQUE INDEX uk_setores_sigla_normalizada ON setores (upper(sigla));

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CHECK (btrim(nome) <> ''),
    descricao VARCHAR(1000),
    setor_id BIGINT NOT NULL REFERENCES setores(id)
);
CREATE INDEX idx_categorias_setor ON categorias(setor_id);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CHECK (btrim(nome) <> ''),
    email VARCHAR(254) NOT NULL CHECK (btrim(email) <> ''),
    matricula VARCHAR(30) NOT NULL CHECK (btrim(matricula) <> ''),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('SOLICITANTE', 'TECNICO')),
    setor_id BIGINT REFERENCES setores(id),
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_tecnico_setor CHECK (tipo <> 'TECNICO' OR setor_id IS NOT NULL)
);
CREATE UNIQUE INDEX uk_usuarios_email_normalizado ON usuarios (lower(email));
CREATE INDEX idx_usuarios_setor ON usuarios(setor_id);
CREATE INDEX idx_usuarios_tipo ON usuarios(tipo);

CREATE TABLE chamados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(160) NOT NULL CHECK (btrim(titulo) <> ''),
    descricao VARCHAR(5000) NOT NULL CHECK (btrim(descricao) <> ''),
    local VARCHAR(200) NOT NULL CHECK (btrim(local) <> ''),
    prioridade VARCHAR(10) NOT NULL DEFAULT 'MEDIA' CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA')),
    status VARCHAR(20) NOT NULL DEFAULT 'ABERTO' CHECK (status IN ('ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO', 'CANCELADO')),
    data_abertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_fechamento TIMESTAMP,
    solucao VARCHAR(5000),
    solicitante_id BIGINT NOT NULL REFERENCES usuarios(id),
    categoria_id BIGINT NOT NULL REFERENCES categorias(id),
    tecnico_id BIGINT REFERENCES usuarios(id),
    CONSTRAINT ck_chamado_fechamento CHECK (
        (status IN ('ABERTO', 'EM_ATENDIMENTO') AND data_fechamento IS NULL)
        OR (status IN ('RESOLVIDO', 'CANCELADO') AND data_fechamento IS NOT NULL)
    ),
    CONSTRAINT ck_chamado_tecnico CHECK (
        (status IN ('ABERTO', 'CANCELADO') AND tecnico_id IS NULL)
        OR (status IN ('EM_ATENDIMENTO', 'RESOLVIDO') AND tecnico_id IS NOT NULL)
    ),
    CONSTRAINT ck_chamado_solucao CHECK (status <> 'RESOLVIDO' OR (solucao IS NOT NULL AND btrim(solucao) <> '')),
    CONSTRAINT ck_chamado_datas CHECK (data_fechamento IS NULL OR data_fechamento >= data_abertura)
);
CREATE INDEX idx_chamados_categoria ON chamados(categoria_id);
CREATE INDEX idx_chamados_solicitante ON chamados(solicitante_id);
CREATE INDEX idx_chamados_tecnico ON chamados(tecnico_id);
CREATE INDEX idx_chamados_status ON chamados(status);
CREATE INDEX idx_chamados_prioridade ON chamados(prioridade);
CREATE INDEX idx_chamados_data_abertura ON chamados(data_abertura);

CREATE TABLE interacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR(5000) NOT NULL CHECK (btrim(texto) <> ''),
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    chamado_id BIGINT NOT NULL REFERENCES chamados(id),
    autor_id BIGINT NOT NULL REFERENCES usuarios(id)
);
CREATE INDEX idx_interacoes_chamado_data ON interacoes(chamado_id, data_hora, id);
CREATE INDEX idx_interacoes_autor ON interacoes(autor_id);
